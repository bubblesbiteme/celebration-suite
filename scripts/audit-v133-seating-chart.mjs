import fs from 'node:fs';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const floor=read('floorplan.html');
const ws=read('event-workspace.html');
const api=read('netlify/functions/floorplans.mjs');
const guests=read('netlify/functions/guest-admin.mjs');
const guestApi=read('netlify/functions/guests.mjs');
const pkg=JSON.parse(read('package.json'));
const sw=read('sw.js');
let pass=0,fail=0;
function check(name,ok){if(ok){console.log('PASS',name);pass++}else{console.error('FAIL',name);fail++}}
check('package version 1.3.3+',/^1\.(?:3\.(?:[3-9]|[1-9][0-9])|[4-9]\.|[1-9][0-9]\.)/.test(pkg.version));
check('service worker cache v133+',/celebration-suite-v(?:13[3-9]|1[4-9][0-9]|[2-9][0-9]{2,})/.test(sw));
check('floorplan backend returns seating guest fields',api.includes('attending_count')&&api.includes('seat_label')&&api.includes('household')&&api.includes('table_name'));
check('guest admin bulk update supports seat_label',guests.includes("if(d.seat_label!==undefined)p.seat_label"));
check('guest API bulk status supports seat_label',guestApi.includes("if('seat_label'in d)patch.seat_label"));
check('standalone seating chart UI exists',floor.includes('id="seatingDesk"')&&floor.includes('id="seatGuestList"')&&floor.includes('id="seatTableList"'));
check('standalone supports drag seating and table select',floor.includes("text/guest-id")&&floor.includes('data-seat-table-for')&&floor.includes('assignGuestToTable'));
check('standalone prevents duplicate seating',floor.includes('removeGuestAssignmentLocal')&&floor.includes('findGuestAssignment'));
check('standalone allocates seats by party size',floor.includes('guestPartySize')&&floor.includes('allocateSeats')&&floor.includes('attending_count'));
check('standalone auto-seat exists',floor.includes('id="autoSeatBtn"')&&floor.includes('function autoSeatGuests'));
check('standalone guest list syncs table and seat',floor.includes("table_name:tableName,seat_label:seat")&&floor.includes("api('guests?id='"));
check('standalone print seating legend exists',floor.includes('id="fpPrintSeating"')&&floor.includes('printSeatingHtml'));
check('event workspace seating chart UI exists',ws.includes('id="adminSeatGuests"')&&ws.includes('id="adminSeatTables"')&&ws.includes('id="adminSeatingSummary"'));
check('event workspace supports drag seating',ws.includes('data-admin-seat-guest')&&ws.includes('data-admin-seat-table-card')&&ws.includes("text/guest-id"));
check('event workspace seat sync includes seat_label',ws.includes("seat_label:seat")&&ws.includes('adminFlushGuestSync'));
check('event workspace auto-seat exists',ws.includes('id="adminAutoSeat"')&&ws.includes('function adminAutoSeat'));
check('event workspace print seating legend exists',ws.includes('id="adminFloorPrintSeating"')&&ws.includes('adminPrintSeatingHtml'));
check('table occupancy is rendered on canvases',floor.includes('seated</span>')&&ws.includes('seated</span>'));
check('new table labels are unique helpers',floor.includes('defaultTableLabel')&&ws.includes('adminDefaultTableLabel'));
check('seat assignments persist in floorplan object JSON',floor.includes('seat_assignments')&&ws.includes('seat_assignments'));
console.log(`\n${pass}/${pass+fail} v1.3.3 seating-chart checks passed.`);
if(fail)process.exit(1);
