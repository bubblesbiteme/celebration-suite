import fs from 'node:fs';
let passed=0, failed=0;
const check=(name,ok,detail='')=>{console.log(`${ok?'PASS':'FAIL'} ${name}${detail?` — ${detail}`:''}`);ok?passed++:failed++};
const ws=fs.readFileSync('event-workspace.html','utf8');
const ultra=fs.readFileSync('assets/ultra-luxury.js','utf8');
const css=fs.readFileSync('assets/ultra-luxury.css','utf8');
check('event workspace reads persisted experience mode',ws.includes("celebration_suite_experience_mode"));
check('guided mode has an explicit essential tab set',ws.includes('const guidedTabs=new Set'));
check('guided mode filters event workspace tabs',ws.includes('tabsForExperience(allowedTabs)'));
check('mode change rerenders event workspace immediately',ws.includes("celebration:experience-mode") && ws.includes("if(data){current='overview';render()"));
check('guided mode visibly changes overview copy',ws.includes('Your planning essentials') && ws.includes('What would you like to do?'));
check('guided mode simplifies quick actions',ws.includes('const quickActions=guidedMode()?'));
check('professional workspace preserves complete tools',ws.includes("'registration'") && ws.includes("'vendors'") && ws.includes("'team'") && ws.includes("'change-orders'"));
check('luxury mode control dispatches experience event',ultra.includes("celebration:experience-mode"));
check('mode preference persists',ultra.includes("localStorage.setItem('celebration_suite_experience_mode',mode)"));
check('desktop search control cannot collapse into stacked text',css.includes('.cs-command-trigger{min-width:108px') && css.includes('white-space:nowrap'));
check('mode control has stable desktop width',css.includes('.cs-luxury-mode-button{min-width:146px'));
console.log(`\nWorkspace modes audit: ${passed}/${passed+failed} passed`);
if(failed) process.exit(1);
