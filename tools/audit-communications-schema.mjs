import fs from 'node:fs';
const checks=[];
const add=(name,ok)=>checks.push({name,ok:Boolean(ok)});
const admin=fs.readFileSync(new URL('../netlify/functions/communications-admin.mjs',import.meta.url),'utf8');
const matcher=fs.readFileSync(new URL('../netlify/functions/_communication-match.mjs',import.meta.url),'utf8');
add('communications does not select nonexistent tenant_events.client_phone',!admin.includes('client_name,client_email,client_phone')&&!/tenant_events[^`]*select=[^`]*client_phone/.test(admin));
add('communications reads event phone from workspace_data',admin.includes('workspace_data?.client_phone'));
add('communications can fall back to tenant client phone',admin.includes('tenant_clients?tenant_id=eq.')&&admin.includes('select=phone'));
add('inbound matcher does not select nonexistent tenant_events.client_phone',!/tenant_events[^`]*select=[^`]*client_phone/.test(matcher));
add('inbound matcher reads event phone from workspace_data',matcher.includes('workspace_data?.client_phone'));
for(const c of checks)console.log(`${c.ok?'PASS':'FAIL'} ${c.name}`);
const passed=checks.filter(c=>c.ok).length;
console.log(`\n${passed}/${checks.length} communications schema checks passed.`);
if(passed!==checks.length)process.exit(1);
