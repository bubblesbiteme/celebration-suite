import fs from 'node:fs';
const read=f=>fs.readFileSync(f,'utf8');
const checks=[];const ok=(n,c)=>checks.push([n,!!c]);
const pkg=JSON.parse(read('package.json'));
const mig=read('supabase/migrations/0028_CONFLICT_REFUND_ACCEPTANCE.sql');
const floor=read('netlify/functions/floorplans.mjs');
const insp=read('netlify/functions/inspiration.mjs');
const client=read('netlify/functions/client-portal.mjs');
const fin=read('netlify/functions/financial-admin.mjs');
const verify=read('netlify/functions/invoice-checkout-verify.mjs');
const domains=read('netlify/functions/custom-domains.mjs');
const domainUi=read('custom-domains.html');
const tests=read('tests/e2e/critical-workflows.spec.mjs');
ok('v0.37+ package lineage',(/^(?:0\.(37|38|39)\.0|1\.0\.[0-9]+)$/).test(pkg.version));
ok('acceptance migration exists',fs.existsSync('supabase/migrations/0028_CONFLICT_REFUND_ACCEPTANCE.sql'));
ok('floorplans have lock version',mig.includes('tenant_floorplans add column if not exists lock_version'));
ok('inspiration has lock version',mig.includes('tenant_inspiration_items add column if not exists lock_version'));
ok('planner floorplan rejects stale updates',floor.includes("code:'EDIT_CONFLICT'")&&floor.includes('lock_version=eq.'));
ok('planner inspiration rejects stale updates',insp.includes("code:'EDIT_CONFLICT'")&&insp.includes('lock_version=eq.'));
ok('client floorplan rejects stale updates',client.includes('The floor plan changed in another session')&&client.includes('expected='));
ok('client inspiration rejects stale updates',client.includes('This design item changed in another session')&&client.includes('expectedDesign'));
ok('floorplan UI sends lock version',read('floorplan.html').includes('lock_version:plan?.lock_version||1'));
ok('inspiration UI sends lock version',read('inspiration.html').includes('lock_version:x.lock_version||1'));
ok('Stripe payment ids stored',mig.includes('stripe_payment_intent_id')&&verify.includes('stripe_payment_intent_id:s.payment_intent'));
ok('refund accounting columns exist',mig.includes('refunded_amount')&&mig.includes('refund_status'));
ok('financial API has Stripe refund action',fin.includes("action==='refundPayment'")&&fin.includes("https://api.stripe.com/v1/refunds"));
ok('refund recalculates invoice state',fin.includes("net<=0?'refunded'")&&fin.includes("net>=Number(inv.amount||0)?'paid':'partial'"));
ok('financial UI exposes refund control',read('financials-admin.html').includes('refundPayment'));
ok('custom domain production diagnostics exist',domains.includes("action==='diagnose'")&&domains.includes('https_ok'));
ok('domain UI exposes DNS SSL test',domainUi.includes('Test DNS & SSL'));
ok('domain diagnostic fields migrate',mig.includes('last_diagnostic_at')&&mig.includes('dns_target'));
ok('release audit includes acceptance audit',pkg.scripts['release:audit'].includes('audit-production-acceptance.mjs'));
ok('browser suite includes conflict acceptance',tests.includes('stale collaboration writes are rejected'));
let fail=0;for(const [n,v] of checks){console.log(`${v?'PASS':'FAIL'} ${n}`);if(!v)fail++}
console.log(`\nProduction acceptance audit: ${checks.length-fail}/${checks.length} passed`);if(fail)process.exit(1);
